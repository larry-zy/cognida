// Command frontend-contracts generates JSON-facing TypeScript DTOs from Go models.
package main

import (
	"bytes"
	c "cognida/internal/model/catalog"
	g "cognida/internal/model/governance"
	l "cognida/internal/model/lifecycle"
	s "cognida/internal/model/semantic"
	u "cognida/internal/model/user"
	"encoding/json"
	"flag"
	"fmt"
	"os"
	"path"
	"reflect"
	"sort"
	"strings"
	"time"
)

var types = map[string]reflect.Type{}
var rawJSON = reflect.TypeOf(json.RawMessage{})
var timestamp = reflect.TypeOf(time.Time{})

func name(t reflect.Type) string {
	p := path.Base(t.PkgPath())
	return strings.ToUpper(p[:1]) + p[1:] + t.Name()
}
func ts(t reflect.Type) string {
	if t == rawJSON {
		return "unknown"
	}
	if t == timestamp {
		return "string"
	}
	switch t.Kind() {
	case reflect.Pointer:
		return ts(t.Elem()) + " | null"
	case reflect.Bool:
		return "boolean"
	case reflect.String:
		return "string"
	case reflect.Int, reflect.Int8, reflect.Int16, reflect.Int32, reflect.Int64, reflect.Uint, reflect.Uint8, reflect.Uint16, reflect.Uint32, reflect.Uint64, reflect.Float32, reflect.Float64:
		return "number"
	case reflect.Interface:
		return "unknown"
	case reflect.Slice:
		if t.Elem().Kind() == reflect.Uint8 {
			return "string | null"
		}
		return "Array<" + ts(t.Elem()) + "> | null"
	case reflect.Array:
		return "Array<" + ts(t.Elem()) + ">"
	case reflect.Map:
		return "Record<string, " + ts(t.Elem()) + "> | null"
	case reflect.Struct:
		n := name(t)
		if _, ok := types[n]; !ok {
			types[n] = t
			fields(t)
		}
		return n
	default:
		panic("unsupported JSON contract type: " + t.String())
	}
}
func fields(t reflect.Type) string {
	var out strings.Builder
	for i := 0; i < t.NumField(); i++ {
		f := t.Field(i)
		if f.PkgPath != "" {
			continue
		}
		tag := strings.Split(f.Tag.Get("json"), ",")
		if tag[0] == "-" {
			continue
		}
		if f.Anonymous && tag[0] == "" {
			ft := f.Type
			if ft.Kind() == reflect.Pointer {
				ft = ft.Elem()
			}
			out.WriteString(fields(ft))
			continue
		}
		key := tag[0]
		if key == "" {
			key = f.Name
		}
		optional := ""
		for _, option := range tag[1:] {
			if option == "omitempty" || option == "omitzero" {
				optional = "?"
			}
		}
		fmt.Fprintf(&out, "  %s%s: %s;\n", key, optional, ts(f.Type))
	}
	return out.String()
}
func generate() []byte {
	roots := []any{l.Input{}, c.Governance{}, g.Meta{}, c.AssetTable{}, c.AssetColumn{}, c.Glossary{}, c.SyncResult{}, l.DataAssetRef{}, l.GateResult{}, l.Output{}, l.AgentContract{}, l.PipelineDefinition{}, l.PipelineRun{}, l.StageRun{}, l.Invocation{}, l.Approval{}, g.Subscription{}, g.SubscriptionRun{}, g.Notification{}, g.AnnotationTask{}, g.AnnotationItem{}, g.TaggingTask{}, g.TaggingResult{}, g.Feature{}, g.FeatureValue{}, g.Suggestion{}, u.Membership{}, s.ModelBundle{}}
	for _, v := range roots {
		ts(reflect.TypeOf(v))
	}
	names := make([]string, 0, len(types))
	for n := range types {
		names = append(names, n)
	}
	sort.Strings(names)
	var out bytes.Buffer
	out.WriteString("// Generated by services/cognida-go/cmd/frontend-contracts. Do not edit.\n// Regenerate: go run ./cmd/frontend-contracts -out ../../apps/cognida-web/src/api/contracts.generated.ts\n")
	for _, n := range names {
		fmt.Fprintf(&out, "export interface %s {\n%s}\n\n", n, fields(types[n]))
	}
	return bytes.TrimSuffix(out.Bytes(), []byte("\n"))
}
func main() {
	output := flag.String("out", "../../apps/cognida-web/src/api/contracts.generated.ts", "output TypeScript file")
	check := flag.Bool("check", false, "fail if tracked contracts differ")
	flag.Parse()
	data := generate()
	if *check {
		actual, err := os.ReadFile(*output)
		if err != nil || !bytes.Equal(actual, data) {
			fmt.Fprintln(os.Stderr, "Frontend contracts differ; run go run ./cmd/frontend-contracts")
			os.Exit(1)
		}
		return
	}
	if err := os.WriteFile(*output, data, 0600); err != nil {
		panic(err)
	}
}
