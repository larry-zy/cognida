CREATE TABLE sandbox_runs (
 id CHAR(36) NOT NULL PRIMARY KEY,
 tenant_id BIGINT NOT NULL,
 user_id BIGINT NOT NULL,
 idempotency_key VARCHAR(128) NOT NULL,
 request_sha256 VARCHAR(71) NOT NULL,
 submission JSON NOT NULL,
 state VARCHAR(32) NOT NULL,
 phase VARCHAR(32) NOT NULL DEFAULT '',
 exec_id VARCHAR(64) NOT NULL DEFAULT '',
 finish_state VARCHAR(32) NOT NULL DEFAULT '',
 finish_error VARCHAR(64) NOT NULL DEFAULT '',
 request_id VARCHAR(128) NOT NULL DEFAULT '',
 version BIGINT NOT NULL DEFAULT 1,
 lease_token CHAR(36) NOT NULL DEFAULT '',
 lease_until DATETIME(6) NULL,
 cancel_requested BOOLEAN NOT NULL DEFAULT FALSE,
 deadline DATETIME(6) NOT NULL,
 manifest JSON NULL,
 output_refs JSON NULL,
 error_code VARCHAR(64) NOT NULL DEFAULT '',
 created_at DATETIME(6) NOT NULL,
 updated_at DATETIME(6) NOT NULL,
 UNIQUE KEY sandbox_owner_key (tenant_id,user_id,idempotency_key),
 KEY sandbox_pending (state,lease_until),
 KEY sandbox_owner_page (tenant_id,user_id,created_at,id)
);
