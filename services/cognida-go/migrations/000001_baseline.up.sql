-- 000001_baseline — 业务表基线（golang-migrate 版本化迁移的起点）〔INF-4〕
--
-- 本基线由当时的 GORM model（cmd/migrate-db 的 AutoMigrate）对空库同步后 mysqldump --no-data 生成，
-- 忠实反映既有 32 张业务表结构。此后所有 schema 变更一律新增版本化迁移文件，不再依赖 AutoMigrate。
-- 存量库接入：先建 schema_migrations 并 `migrate force 1` 标记本基线为已应用（不重复建表）；
-- 全新库：直接 `migrate up` 由本文件建表。图谱本体在 Neo4j（见〔GO-3〕），不在此列。

